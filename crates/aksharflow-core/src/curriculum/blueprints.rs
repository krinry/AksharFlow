use serde::{Deserialize, Serialize};

use crate::keymap::LayoutKind;

/// Broad pedagogical phase grouping the 28 curriculum units.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "specta-types", derive(specta::Type))]
#[serde(rename_all = "snake_case")]
pub enum CurriculumStage {
    HomeRow,
    TopRowAndMatras,
    BottomRowAndConjuncts,
    ShiftNumbersAndSymbols,
    FluencyAndStories,
}

/// Static blueprint describing one unit in a layout's 28-unit curriculum.
#[derive(Debug, Clone, Copy)]
pub struct UnitBlueprint {
    pub unit_number: u32,
    pub stage: CurriculumStage,
    pub title_en: &'static str,
    pub title_hi: &'static str,
    pub focus_keys: &'static [&'static str],
    pub target_wpm: f64,
    pub min_accuracy: f64,
    pub sample_phrases: &'static [&'static str],
}

pub fn blueprints_for_layout(layout: LayoutKind) -> &'static [UnitBlueprint] {
    match layout {
        LayoutKind::EnQwerty => &EN_QWERTY_UNITS,
        LayoutKind::HiInscript => &HI_INSCRIPT_UNITS,
        LayoutKind::HiRemingtonGail => &HI_REMINGTON_UNITS,
    }
}

